// Клиентско-серверные demo-ответы Beauty AI.
// Используются и на сервере (/api/chat без ключа), и на клиенте (fallback, например на GitHub Pages).

export function demoReply(userText: string): string {
  const t = userText.toLowerCase();

  if (/(волос|осветл|блонд|сух|секущ|маск)/.test(t)) {
    return (
      'Отличный вопрос про волосы! Короткая основа ухода:\n\n' +
      '1. Мягкое очищение — шампунь без агрессивных сульфатов, вода тёплая, не горячая.\n' +
      '2. Кондиционер после каждого мытья — на длину и концы, выдерживайте 2–3 минуты.\n' +
      '3. Питательная маска 1–2 раза в неделю, эффект накопительный.\n' +
      '4. Несмываемый крем после мытья — защищает в течение дня.\n' +
      '5. Термозащита перед феном, утюжком или плойкой — всегда.\n\n' +
      'Если волосы осветлённые, загляните в наш интерактивный тест восстановления волос на главной странице — он соберёт для вас персональный план. 💛'
    );
  }

  if (/(кож|лицо|уход за кожей|морщин|крем|сыворотк)/.test(t)) {
    return (
      'Простая рабочая система ухода за кожей:\n\n' +
      '• Утро: мягкое очищение → увлажняющий крем → SPF (это самый важный шаг).\n' +
      '• Вечер: очищение → увлажнение; 2–3 раза в неделю можно добавить сыворотку.\n\n' +
      'Новое средство вводите по одному и наблюдайте 2–3 недели. Если вопрос касается высыпаний, раздражений или других изменений кожи, лучше обратиться к дерматологу очно. 🌿'
    );
  }

  if (/(упражн|тренир|форм|активн|спорт|присед|растяжк|зарядк)/.test(t)) {
    return (
      'Для дома отлично работают короткие программы:\n\n' +
      '• Лёгкая разминка — 2 минуты (вращения плечами, шаги на месте).\n' +
      '• Приседания с собственным весом — 10–12 повторений.\n' +
      '• Ягодичный мост — 12 повторений.\n' +
      '• Движения для плеч — 1 минута.\n' +
      '• Лёгкая растяжка — 2–3 минуты.\n\n' +
      'На главной странице есть генератор программ: выберите цель, уровень, время и пространство — и получите программу на день. ✨'
    );
  }

  if (/(макияж|тон|консилер|тушь)/.test(t)) {
    return (
      'Главный принцип современного макияжа — лёгкость: не «замазать», а выровнять.\n\n' +
      '• База начинается с ухода: увлажнение перед макияжем даёт более ровное покрытие.\n' +
      '• Консилер — точечно, румяна — кремовые, ближе к яблочкам щёк.\n' +
      '• Кисти мойте раз в неделю — это влияет и на покрытие, и на кожу.'
    );
  }

  if (/(гороскоп|знак|астр)/.test(t)) {
    return 'Наш гороскоп на сегодня — в разделе «Гороскоп» на главной странице: выберите знак, и мы покажем прогноз по отношениям, работе, финансам и самочувствию. ✨ Он носит развлекательный характер.';
  }

  if (/(погод|дожд|температур)/.test(t)) {
    return 'Проверить погоду можно в блоке «Сегодня для тебя» — выберите город, и мы покажем температуру, ощущаемую погоду, осадки и прогноз на несколько дней.';
  }

  return (
    'Спасибо за вопрос! Я — Beauty Room AI, помогаю по темам красоты, ухода, волос, лёгкой активности и образа жизни.\n\n' +
    'Попробуйте спросить, например:\n' +
    '• «Как ухаживать за сухими волосами?»\n' +
    '• «Как составить простой уход за кожей?»\n' +
    '• «Какие лёгкие упражнения можно делать дома?»\n\n' +
    'И помните: по медицинским вопросам лучший советчик — профильный специалист. 💛'
  );
}
