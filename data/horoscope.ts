export function getHoroscope(signIndex: number, now: Date = new Date()): HoroscopeResult {
  const start = new Date(now.getFullYear(), 0, 0);
  const dayOfYear = Math.floor((now.getTime() - start.getTime()) / 86400000);
  const pick = (pool: string[], salt: number) =>
    pool[(dayOfYear * 7 + signIndex * 13 + salt) % pool.length];

  return {
    love: pick(LOVE, 1),
    work: pick(WORK, 2),
    money: pick(MONEY, 3),
    mood: pick(MOOD, 4),
    health: pick(HEALTH, 5),
    advice: pick(ADVICE, 6),
    date: now.toLocaleDateString('ru-RU', { day: 'numeric', month: 'long', year: 'numeric' }),
  };
}
