export interface QuizAnswers {
  [key: string]: string;
}

export function getBeauty30Recommendations(a: QuizAnswers): { title: string; text: string }[] {
  const recs: { title: string; text: string }[] = [];

  const dry = a.skinType === 'Сухая';
  const oily = a.skinType === 'Жирная';
  const sensitive = a.sensitivity === 'Высокая';

  recs.push({
    title: 'Утренний уход',
    text: dry
      ? 'Мягкое очищение без пенки со скрипом, плотный увлажняющий крем и SPF — обязательный последний шаг.'
      : oily
        ? 'Лёгкое очищение, увлажняющий гель и SPF с лёгкой текстурой. Без спиртовых тоников — они усиливают жирность.'
        : 'Очищение, увлажняющая эмульсия или крем и SPF. Трёх шагов утром достаточно.',
  });

  recs.push({
    title: 'Вечерний уход',
    text: sensitive
      ? 'Очищение и успокаивающий крем. Новые активы (кислоты, ретинол) вводите очень осторожно и по одному, начиная с 1 раза в неделю.'
      : 'Очищение, увлажнение. Если базовый режим освоен, 2–3 раза в неделю можно добавить мягкую регенерирующую сыворотку.',
  });

  recs.push({
    title: 'По вашей задаче',
    text:
      a.goal === 'Увлажнение'
        ? 'Сфокусируйтесь на влагоудерживающих компонентах: гиалуроновая кислота, церамиды, глицерин. Наносите крем на слегка влажную кожу.'
        : a.goal === 'Пигментация'
          ? 'Главный инструмент — ежедневный SPF даже зимой и в облачную погоду. Дополнительно в уход можно вводить осветляющие и мягко обновляющие компоненты, лучше после очной консультации.'
          : a.goal === 'Тон и сияние'
            ? 'Помогают регулярное мягкое отшелушивание (1–2 раза в неделю), достаточный сон и движение. Тусклость часто связана не с кремами, а с образом жизни.'
            : a.goal === 'Первые возрастные изменения'
              ? 'База — SPF и увлажнение. Следующий шаг — регенерирующие компоненты (например, ретинол) введённые аккуратно: с низкой концентрации, 2–3 раза в неделю, вечером.'
              : 'Профилактика — это прежде всего стабильность: SPF, увлажнение, сон и вода. Сложные схемы не нужны.',
  });

  recs.push({
    title: 'Образ жизни',
    text:
      a.homecare === 'Минимальный'
        ? 'Начните с малого: умывание + крем + SPF стабильно каждый день. Регулярность даст больше, чем редкие «процедуры» из трёх сывороток.'
        : 'Поддержите уход снаружи изнутри: сон 7–9 часов, достаточно воды и лёгкая активность ежедневно.',
  });

  recs.push({
    title: 'Косметолог',
    text:
      a.cosmetologist === 'Никогда'
        ? 'Если есть возможность, начните с одной очной консультации: специалист оценит кожу и подскажет, что актуально именно вам, без лишних процедур.'
        : a.cosmetologist === 'Иногда'
          ? 'Стабильный график (2–4 раза в год) работает лучше разовых визитов «по случаю». Обсудите со специалистом поддерживающий, а не «авральный» план.'
          : 'Регулярные визиты — отлично. Периодически сверяйте домашний уход с рекомендациями специалиста: потребности кожи меняются.',
  });

  return recs;
}
